using System;
using System.Collections.Generic;
using System.Linq;
using 题库核心.内容块模块.契约;
using 题库核心.内容块模块.领域;
using 题库核心.讲义模块.契约;
using 题库核心.讲义模块.领域;
using 题库核心.小节模块.契约;
using 题库核心.小节模块.领域;

namespace 题库应用.讲义模块
{
    public class 获取讲义结构树用例
    {
        private const int 最大展开深度 = 20;

        private readonly I讲义仓储 _讲义仓储;
        private readonly I小节仓储 _小节仓储;
        private readonly I内容块仓储 _内容块仓储;

        public 获取讲义结构树用例(
            I讲义仓储 讲义仓储,
            I小节仓储 小节仓储,
            I内容块仓储 内容块仓储)
        {
            _讲义仓储 = 讲义仓储;
            _小节仓储 = 小节仓储;
            _内容块仓储 = 内容块仓储;
        }

        public 讲义结构树结果? 执行(int 讲义ID)
        {
            var 讲义 = _讲义仓储.GetById(讲义ID);
            if (讲义 == null)
            {
                return null;
            }

            var 根节点 = new 讲义结构树结果
            {
                节点ID = $"讲义-{讲义.Id}",
                节点类型 = "讲义",
                目标ID = 讲义.Id,
                标题 = 讲义.标题,
                摘要 = 讲义.摘要,
                状态 = 讲义.状态.ToString(),
                深度 = 0,
                更新时间 = 讲义.更新时间,
                可执行操作 = new List<string> { "添加小节", "添加内容块" },
            };

            foreach (var 讲义项 in _讲义仓储.获取讲义项列表(讲义.Id).OrderBy(项 => 项.排序).ThenBy(项 => 项.Id))
            {
                根节点.子节点列表.Add(构建讲义项节点(讲义项, 1));
            }

            根节点.子节点数量 = 根节点.子节点列表.Count;
            return 根节点;
        }

        private 讲义结构树结果 构建讲义项节点(讲义项 讲义项, int 深度)
        {
            if (讲义项.目标类型 == 讲义项目标类型.小节)
            {
                return 构建小节节点(讲义项, 深度);
            }

            return 构建内容块节点(
                讲义项.目标ID,
                "讲义项",
                讲义项.Id,
                讲义项.讲义ID,
                讲义项.角色,
                讲义项.引用版本模式,
                讲义项.锁定内容块版本ID,
                讲义项.排序,
                深度,
                new HashSet<int>());
        }

        private 讲义结构树结果 构建小节节点(讲义项 讲义项, int 深度)
        {
            var 小节 = _小节仓储.GetById(讲义项.目标ID);
            if (小节 == null)
            {
                return 构建错误节点(
                    $"讲义项-{讲义项.Id}",
                    "小节",
                    "讲义项",
                    讲义项.Id,
                    讲义项.讲义ID,
                    讲义项.目标ID,
                    讲义项.排序,
                    深度,
                    "引用的小节不存在。");
            }

            var 节点 = new 讲义结构树结果
            {
                节点ID = $"讲义项-{讲义项.Id}",
                节点类型 = "小节",
                目标ID = 小节.Id,
                标题 = 小节.标题,
                摘要 = 小节.摘要,
                状态 = 小节.状态.ToString(),
                章节标签ID = 小节.章节标签ID,
                来源类型 = "讲义项",
                来源ID = 讲义项.Id,
                父目标ID = 讲义项.讲义ID,
                角色 = 讲义项.角色,
                排序 = 讲义项.排序,
                深度 = 深度,
                更新时间 = 小节.更新时间,
                可执行操作 = new List<string> { "上移", "下移", "移除", "编辑小节", "添加内容块" },
            };

            foreach (var 小节项 in _小节仓储.获取小节项列表(小节.Id).OrderBy(项 => 项.排序).ThenBy(项 => 项.Id))
            {
                节点.子节点列表.Add(构建内容块节点(
                    小节项.内容块ID,
                    "小节项",
                    小节项.Id,
                    小节.Id,
                    小节项.角色,
                    小节项.引用版本模式,
                    小节项.内容块版本ID,
                    小节项.排序,
                    深度 + 1,
                    new HashSet<int>()));
            }

            节点.子节点数量 = 节点.子节点列表.Count;
            return 节点;
        }

        private 讲义结构树结果 构建内容块节点(
            int 内容块ID,
            string 来源类型,
            int 来源ID,
            int 父目标ID,
            string? 角色,
            内容块引用版本模式 引用版本模式,
            int? 锁定版本ID,
            int 排序,
            int 深度,
            ISet<int> 路径内容块ID集合)
        {
            var 内容块 = _内容块仓储.GetById(内容块ID);
            if (内容块 == null)
            {
                return 构建错误节点(
                    $"{来源类型}-{来源ID}",
                    "内容块",
                    来源类型,
                    来源ID,
                    父目标ID,
                    内容块ID,
                    排序,
                    深度,
                    "引用的内容块不存在。");
            }

            var 引用版本 = 获取引用版本(内容块.Id, 引用版本模式, 锁定版本ID);
            var 节点 = new 讲义结构树结果
            {
                节点ID = $"{来源类型}-{来源ID}",
                节点类型 = "内容块",
                目标ID = 内容块.Id,
                标题 = 内容块.标题,
                摘要 = 内容块.摘要,
                状态 = 内容块.状态.ToString(),
                内容类型 = 内容块.类型.ToString(),
                结构类型 = 内容块.结构类型.ToString(),
                是否允许子块 = 内容块.是否允许子块,
                当前版本ID = 内容块.当前版本ID,
                当前版本号 = _内容块仓储.获取当前版本(内容块.Id)?.版本号,
                来源类型 = 来源类型,
                来源ID = 来源ID,
                父目标ID = 父目标ID,
                角色 = 角色,
                引用版本模式 = 引用版本模式.ToString(),
                引用版本ID = 引用版本?.Id,
                引用版本号 = 引用版本?.版本号,
                排序 = 排序,
                深度 = 深度,
                更新时间 = 内容块.更新时间,
                可执行操作 = 内容块.是否允许子块
                    ? new List<string> { "上移", "下移", "移除", "编辑Word", "添加子内容块" }
                    : new List<string> { "上移", "下移", "移除", "编辑Word" },
            };

            if (!内容块.是否允许子块)
            {
                return 节点;
            }

            if (深度 >= 最大展开深度)
            {
                节点.子节点列表.Add(构建错误节点(
                    $"深度限制-{内容块.Id}",
                    "错误",
                    "内容块",
                    内容块.Id,
                    内容块.Id,
                    内容块.Id,
                    0,
                    深度 + 1,
                    $"已达到最大展开深度 {最大展开深度}。"));
                节点.子节点数量 = 节点.子节点列表.Count;
                return 节点;
            }

            if (!路径内容块ID集合.Add(内容块.Id))
            {
                节点.子节点列表.Add(构建错误节点(
                    $"循环引用-{内容块.Id}",
                    "错误",
                    "内容块",
                    内容块.Id,
                    内容块.Id,
                    内容块.Id,
                    0,
                    深度 + 1,
                    "检测到循环嵌套，已停止展开。"));
                节点.子节点数量 = 节点.子节点列表.Count;
                return 节点;
            }

            foreach (var 子项 in _内容块仓储.获取子项列表(内容块.Id).OrderBy(项 => 项.排序).ThenBy(项 => 项.Id))
            {
                节点.子节点列表.Add(构建内容块节点(
                    子项.子内容块ID,
                    "内容块子项",
                    子项.Id,
                    内容块.Id,
                    子项.角色,
                    子项.引用版本模式,
                    子项.子内容块版本ID,
                    子项.排序,
                    深度 + 1,
                    new HashSet<int>(路径内容块ID集合)));
            }

            节点.子节点数量 = 节点.子节点列表.Count;
            return 节点;
        }

        private 内容块版本? 获取引用版本(int 内容块ID, 内容块引用版本模式 引用版本模式, int? 锁定版本ID)
        {
            if (引用版本模式 == 内容块引用版本模式.锁定版本 && 锁定版本ID.HasValue)
            {
                return _内容块仓储.获取版本(锁定版本ID.Value);
            }

            return _内容块仓储.获取当前版本(内容块ID);
        }

        private static 讲义结构树结果 构建错误节点(
            string 节点ID,
            string 节点类型,
            string 来源类型,
            int 来源ID,
            int 父目标ID,
            int 目标ID,
            int 排序,
            int 深度,
            string 错误信息)
        {
            return new 讲义结构树结果
            {
                节点ID = 节点ID,
                节点类型 = 节点类型,
                目标ID = 目标ID,
                标题 = "引用异常",
                来源类型 = 来源类型,
                来源ID = 来源ID,
                父目标ID = 父目标ID,
                排序 = 排序,
                深度 = 深度,
                是否错误 = true,
                错误信息 = 错误信息,
                可执行操作 = new List<string> { "移除" },
            };
        }
    }
}

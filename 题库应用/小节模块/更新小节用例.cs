using 题库核心.小节模块.契约;

namespace 题库应用.小节模块
{
    public class 更新小节用例
    {
        private readonly I小节仓储 _小节仓储;
        private readonly 小节章节规则校验器 _小节章节规则校验器;
        private readonly 小节结果构建器 _小节结果构建器;

        public 更新小节用例(
            I小节仓储 小节仓储,
            小节章节规则校验器 小节章节规则校验器,
            小节结果构建器 小节结果构建器)
        {
            _小节仓储 = 小节仓储;
            _小节章节规则校验器 = 小节章节规则校验器;
            _小节结果构建器 = 小节结果构建器;
        }

        public 小节详情结果? 执行(int id, 更新小节的请求 请求)
        {
            var 小节 = _小节仓储.GetById(id);
            if (小节 == null)
            {
                return null;
            }

            _小节章节规则校验器.校验并返回章节标签(请求.章节标签ID);
            小节.修改元数据(请求.标题, 请求.摘要, 请求.章节标签ID, 请求.状态);
            _小节仓储.保存小节(小节);
            return _小节结果构建器.构建详情(小节);
        }
    }
}

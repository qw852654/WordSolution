using System;
using System.Collections.Generic;
using System.Linq;
using 题库核心.内容块模块.契约;
using 题库核心.内容块模块.领域;
using 题库核心.讲义模块.契约;
using 题库核心.讲义模块.领域;
using 题库核心.小节模块.契约;

namespace 题库应用.引用关系模块
{
    public class 引用关系分析器
    {
        private readonly I内容块仓储 _内容块仓储;
        private readonly I小节仓储 _小节仓储;
        private readonly I讲义仓储 _讲义仓储;

        public 引用关系分析器(
            I内容块仓储 内容块仓储,
            I小节仓储 小节仓储,
            I讲义仓储 讲义仓储)
        {
            _内容块仓储 = 内容块仓储;
            _小节仓储 = 小节仓储;
            _讲义仓储 = 讲义仓储;
        }

        public 内容块引用影响结果? 分析内容块影响(int 内容块ID)
        {
            var 内容块 = _内容块仓储.GetById(内容块ID);
            if (内容块 == null)
            {
                return null;
            }

            var 当前版本 = _内容块仓储.获取当前版本(内容块ID);
            var 路径列表 = 获取内容块引用路径列表(内容块, 当前版本);
            var 引用位置列表 = new List<引用位置结果>();

            引用位置列表.AddRange(构建组合块引用位置(路径列表));
            引用位置列表.AddRange(构建小节引用位置(内容块, 当前版本, 路径列表));
            引用位置列表.AddRange(构建讲义引用位置(内容块, 当前版本, 路径列表));

            var 旧版本引用列表 = 引用位置列表
                .Where(位置 => 位置.是否锁定旧版本)
                .Select(位置 => new 旧版本引用结果
                {
                    内容块ID = 内容块.Id,
                    内容块标题 = 内容块.标题,
                    当前版本ID = 当前版本?.Id,
                    当前版本号 = 当前版本?.版本号,
                    引用类型 = 位置.引用类型,
                    引用对象ID = 位置.引用对象ID,
                    引用对象标题 = 位置.引用对象标题,
                    引用项ID = 位置.引用项ID,
                    引用版本模式 = 位置.引用版本模式 ?? 内容块引用版本模式.跟随最新,
                    锁定内容块版本ID = 位置.锁定内容块版本ID,
                    锁定版本号 = 位置.锁定版本号,
                    引用链 = 位置.引用链
                })
                .ToList();

            return new 内容块引用影响结果
            {
                内容块ID = 内容块.Id,
                内容块标题 = 内容块.标题,
                当前版本ID = 当前版本?.Id,
                当前版本号 = 当前版本?.版本号,
                组合块引用数量 = 引用位置列表.Count(位置 => 位置.引用类型 == "组合块"),
                小节引用数量 = 引用位置列表.Count(位置 => 位置.引用类型 == "小节"),
                讲义引用数量 = 引用位置列表.Count(位置 => 位置.引用类型 == "讲义"),
                锁定旧版本数量 = 旧版本引用列表.Count,
                引用位置列表 = 引用位置列表,
                旧版本引用列表 = 旧版本引用列表
            };
        }

        public IReadOnlyList<旧版本引用结果> 获取全部旧版本引用()
        {
            return _内容块仓储.查询内容块(null, null, null)
                .Select(内容块 => 分析内容块影响(内容块.Id))
                .Where(结果 => 结果 != null)
                .Cast<内容块引用影响结果>()
                .SelectMany(结果 => 结果.旧版本引用列表)
                .OrderBy(引用 => 引用.内容块标题)
                .ThenBy(引用 => 引用.引用类型)
                .ThenBy(引用 => 引用.引用对象标题)
                .ToList();
        }

        private IReadOnlyList<内容块引用路径> 获取内容块引用路径列表(内容块 内容块, 内容块版本? 当前版本)
        {
            var 路径列表 = new List<内容块引用路径>
            {
                new 内容块引用路径
                {
                    入口内容块ID = 内容块.Id,
                    入口内容块标题 = 内容块.标题,
                    引用链 = 内容块.标题,
                    是否自身 = true,
                    是否直接父级 = false,
                    目标直接父级关系 = null,
                    是否锁定目标旧版本 = false,
                    锁定内容块版本ID = null,
                    锁定版本号 = null
                }
            };

            递归收集父级路径(内容块, 内容块.Id, 内容块.标题, null, 当前版本, new HashSet<int> { 内容块.Id }, 路径列表);
            return 路径列表;
        }

        private void 递归收集父级路径(
            内容块 目标内容块,
            int 当前入口内容块ID,
            string 当前链,
            内容块子项? 目标直接父级关系,
            内容块版本? 目标当前版本,
            HashSet<int> 已访问内容块ID集合,
            List<内容块引用路径> 路径列表)
        {
            foreach (var 父项关系 in _内容块仓储.获取父项列表(当前入口内容块ID))
            {
                if (!已访问内容块ID集合.Add(父项关系.父内容块ID))
                {
                    continue;
                }

                var 父内容块 = _内容块仓储.GetById(父项关系.父内容块ID);
                if (父内容块 == null)
                {
                    已访问内容块ID集合.Remove(父项关系.父内容块ID);
                    continue;
                }

                var 实际目标直接父级关系 = 当前入口内容块ID == 目标内容块.Id
                    ? 父项关系
                    : 目标直接父级关系;
                var 锁定版本号 = 实际目标直接父级关系?.子内容块版本ID.HasValue == true
                    ? _内容块仓储.获取版本(实际目标直接父级关系.子内容块版本ID.Value)?.版本号
                    : null;
                var 是否锁定目标旧版本 = 是否锁定旧版本(
                    实际目标直接父级关系?.引用版本模式,
                    实际目标直接父级关系?.子内容块版本ID,
                    目标当前版本);

                var 新链 = $"{父内容块.标题} > {当前链}";
                路径列表.Add(new 内容块引用路径
                {
                    入口内容块ID = 父内容块.Id,
                    入口内容块标题 = 父内容块.标题,
                    引用链 = 新链,
                    是否自身 = false,
                    是否直接父级 = 当前入口内容块ID == 目标内容块.Id,
                    目标直接父级关系 = 实际目标直接父级关系,
                    是否锁定目标旧版本 = 是否锁定目标旧版本,
                    锁定内容块版本ID = 实际目标直接父级关系?.子内容块版本ID,
                    锁定版本号 = 锁定版本号
                });

                递归收集父级路径(
                    目标内容块,
                    父内容块.Id,
                    新链,
                    实际目标直接父级关系,
                    目标当前版本,
                    已访问内容块ID集合,
                    路径列表);

                已访问内容块ID集合.Remove(父项关系.父内容块ID);
            }
        }

        private IEnumerable<引用位置结果> 构建组合块引用位置(IReadOnlyList<内容块引用路径> 路径列表)
        {
            return 路径列表
                .Where(路径 => !路径.是否自身)
                .Select(路径 => new 引用位置结果
                {
                    引用类型 = "组合块",
                    引用对象ID = 路径.入口内容块ID,
                    引用对象标题 = 路径.入口内容块标题,
                    引用项ID = 路径.目标直接父级关系?.Id,
                    是否直接引用 = 路径.是否直接父级,
                    引用链 = 路径.引用链,
                    引用版本模式 = 路径.目标直接父级关系?.引用版本模式,
                    锁定内容块版本ID = 路径.锁定内容块版本ID,
                    锁定版本号 = 路径.锁定版本号,
                    是否锁定旧版本 = 路径.是否锁定目标旧版本,
                    说明 = 路径.是否直接父级 ? "组合块直接包含该内容块。" : "组合块通过子块链间接包含该内容块。"
                });
        }

        private IEnumerable<引用位置结果> 构建小节引用位置(
            内容块 目标内容块,
            内容块版本? 目标当前版本,
            IReadOnlyList<内容块引用路径> 路径列表)
        {
            var 路径字典 = 路径列表
                .GroupBy(路径 => 路径.入口内容块ID)
                .ToDictionary(分组 => 分组.Key, 分组 => 分组.ToList());

            foreach (var 小节 in _小节仓储.查询小节(null, null, null))
            {
                foreach (var 小节项 in _小节仓储.获取小节项列表(小节.Id))
                {
                    if (!路径字典.TryGetValue(小节项.内容块ID, out var 匹配路径列表))
                    {
                        continue;
                    }

                    foreach (var 路径 in 匹配路径列表)
                    {
                        var 直接引用目标 = 小节项.内容块ID == 目标内容块.Id;
                        var 直接旧版本 = 直接引用目标 && 是否锁定旧版本(小节项.引用版本模式, 小节项.内容块版本ID, 目标当前版本);
                        var 锁定版本ID = 直接引用目标 ? 小节项.内容块版本ID : 路径.锁定内容块版本ID;
                        var 锁定版本号 = 锁定版本ID.HasValue ? _内容块仓储.获取版本(锁定版本ID.Value)?.版本号 : null;

                        yield return new 引用位置结果
                        {
                            引用类型 = "小节",
                            引用对象ID = 小节.Id,
                            引用对象标题 = 小节.标题,
                            引用项ID = 小节项.Id,
                            是否直接引用 = 直接引用目标,
                            引用链 = $"{小节.标题} > {路径.引用链}",
                            引用版本模式 = 直接引用目标 ? 小节项.引用版本模式 : 路径.目标直接父级关系?.引用版本模式,
                            锁定内容块版本ID = 锁定版本ID,
                            锁定版本号 = 锁定版本号,
                            是否锁定旧版本 = 直接旧版本 || 路径.是否锁定目标旧版本,
                            说明 = 直接引用目标 ? "小节直接引用该内容块。" : "小节引用了包含该内容块的组合块。"
                        };
                    }
                }
            }
        }

        private IEnumerable<引用位置结果> 构建讲义引用位置(
            内容块 目标内容块,
            内容块版本? 目标当前版本,
            IReadOnlyList<内容块引用路径> 路径列表)
        {
            var 路径字典 = 路径列表
                .GroupBy(路径 => 路径.入口内容块ID)
                .ToDictionary(分组 => 分组.Key, 分组 => 分组.ToList());

            foreach (var 讲义 in _讲义仓储.查询讲义(null, null))
            {
                foreach (var 讲义项 in _讲义仓储.获取讲义项列表(讲义.Id))
                {
                    if (讲义项.目标类型 == 讲义项目标类型.内容块)
                    {
                        foreach (var 位置 in 构建直接内容块讲义引用(讲义, 讲义项, 目标内容块, 目标当前版本, 路径字典))
                        {
                            yield return 位置;
                        }
                    }
                    else if (讲义项.目标类型 == 讲义项目标类型.小节)
                    {
                        foreach (var 位置 in 构建小节讲义引用(讲义, 讲义项, 目标内容块, 目标当前版本, 路径字典))
                        {
                            yield return 位置;
                        }
                    }
                }
            }
        }

        private IEnumerable<引用位置结果> 构建直接内容块讲义引用(
            讲义 讲义,
            讲义项 讲义项,
            内容块 目标内容块,
            内容块版本? 目标当前版本,
            IReadOnlyDictionary<int, List<内容块引用路径>> 路径字典)
        {
            if (!路径字典.TryGetValue(讲义项.目标ID, out var 匹配路径列表))
            {
                yield break;
            }

            foreach (var 路径 in 匹配路径列表)
            {
                var 直接引用目标 = 讲义项.目标ID == 目标内容块.Id;
                var 直接旧版本 = 直接引用目标 && 是否锁定旧版本(讲义项.引用版本模式, 讲义项.锁定内容块版本ID, 目标当前版本);
                var 锁定版本ID = 直接引用目标 ? 讲义项.锁定内容块版本ID : 路径.锁定内容块版本ID;
                var 锁定版本号 = 锁定版本ID.HasValue ? _内容块仓储.获取版本(锁定版本ID.Value)?.版本号 : null;

                yield return new 引用位置结果
                {
                    引用类型 = "讲义",
                    引用对象ID = 讲义.Id,
                    引用对象标题 = 讲义.标题,
                    引用项ID = 讲义项.Id,
                    是否直接引用 = 直接引用目标,
                    引用链 = $"{讲义.标题} > {路径.引用链}",
                    引用版本模式 = 直接引用目标 ? 讲义项.引用版本模式 : 路径.目标直接父级关系?.引用版本模式,
                    锁定内容块版本ID = 锁定版本ID,
                    锁定版本号 = 锁定版本号,
                    是否锁定旧版本 = 直接旧版本 || 路径.是否锁定目标旧版本,
                    说明 = 直接引用目标 ? "讲义直接引用该内容块。" : "讲义引用了包含该内容块的组合块。"
                };
            }
        }

        private IEnumerable<引用位置结果> 构建小节讲义引用(
            讲义 讲义,
            讲义项 讲义项,
            内容块 目标内容块,
            内容块版本? 目标当前版本,
            IReadOnlyDictionary<int, List<内容块引用路径>> 路径字典)
        {
            var 小节 = _小节仓储.GetById(讲义项.目标ID);
            if (小节 == null)
            {
                yield break;
            }

            foreach (var 小节项 in _小节仓储.获取小节项列表(小节.Id))
            {
                if (!路径字典.TryGetValue(小节项.内容块ID, out var 匹配路径列表))
                {
                    continue;
                }

                foreach (var 路径 in 匹配路径列表)
                {
                    var 直接引用目标 = 小节项.内容块ID == 目标内容块.Id;
                    var 直接旧版本 = 直接引用目标 && 是否锁定旧版本(小节项.引用版本模式, 小节项.内容块版本ID, 目标当前版本);
                    var 锁定版本ID = 直接引用目标 ? 小节项.内容块版本ID : 路径.锁定内容块版本ID;
                    var 锁定版本号 = 锁定版本ID.HasValue ? _内容块仓储.获取版本(锁定版本ID.Value)?.版本号 : null;

                    yield return new 引用位置结果
                    {
                        引用类型 = "讲义",
                        引用对象ID = 讲义.Id,
                        引用对象标题 = 讲义.标题,
                        引用项ID = 讲义项.Id,
                        是否直接引用 = false,
                        引用链 = $"{讲义.标题} > {小节.标题} > {路径.引用链}",
                        引用版本模式 = 直接引用目标 ? 小节项.引用版本模式 : 路径.目标直接父级关系?.引用版本模式,
                        锁定内容块版本ID = 锁定版本ID,
                        锁定版本号 = 锁定版本号,
                        是否锁定旧版本 = 直接旧版本 || 路径.是否锁定目标旧版本,
                        说明 = 直接引用目标 ? "讲义引用的小节直接包含该内容块。" : "讲义引用的小节通过组合块包含该内容块。"
                    };
                }
            }
        }

        private bool 是否锁定旧版本(内容块引用版本模式? 引用版本模式, int? 锁定版本ID, 内容块版本? 当前版本)
        {
            return 引用版本模式 == 内容块引用版本模式.锁定版本
                && 锁定版本ID.HasValue
                && 当前版本 != null
                && 锁定版本ID.Value != 当前版本.Id;
        }

        private class 内容块引用路径
        {
            public int 入口内容块ID { get; set; }

            public string 入口内容块标题 { get; set; } = string.Empty;

            public string 引用链 { get; set; } = string.Empty;

            public bool 是否自身 { get; set; }

            public bool 是否直接父级 { get; set; }

            public 内容块子项? 目标直接父级关系 { get; set; }

            public bool 是否锁定目标旧版本 { get; set; }

            public int? 锁定内容块版本ID { get; set; }

            public int? 锁定版本号 { get; set; }
        }
    }
}

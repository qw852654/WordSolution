using 题库核心.内容块模块.契约;

namespace 题库应用.内容块模块
{
    public class 取消内容块编辑会话用例
    {
        private readonly I内容块编辑会话存储 _内容块编辑会话存储;
        private readonly I内容块编辑会话文件存储 _内容块编辑会话文件存储;

        public 取消内容块编辑会话用例(
            I内容块编辑会话存储 内容块编辑会话存储,
            I内容块编辑会话文件存储 内容块编辑会话文件存储)
        {
            _内容块编辑会话存储 = 内容块编辑会话存储;
            _内容块编辑会话文件存储 = 内容块编辑会话文件存储;
        }

        public 内容块编辑会话结果? 执行(string 会话ID)
        {
            var 会话 = _内容块编辑会话存储.获取(会话ID);
            if (会话 == null)
            {
                return null;
            }

            lock (会话)
            {
                if (!会话.是终态())
                {
                    会话.标记已取消();
                    _内容块编辑会话文件存储.写入会话信息(会话);
                }
            }

            return 内容块编辑会话结果.从会话(会话);
        }
    }
}

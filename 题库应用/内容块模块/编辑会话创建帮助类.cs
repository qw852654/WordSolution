using System;
using 题库核心.内容块模块.契约;
using 题库核心.内容块模块.领域;

namespace 题库应用.内容块模块
{
    public class 编辑会话创建帮助类
    {
        private readonly I内容块编辑会话存储 _内容块编辑会话存储;
        private readonly I内容块编辑会话文件存储 _内容块编辑会话文件存储;
        private readonly I内容块文档转换器 _内容块文档转换器;
        private readonly I文件哈希服务 _文件哈希服务;
        private readonly I本地Word启动器 _本地Word启动器;

        public 编辑会话创建帮助类(
            I内容块编辑会话存储 内容块编辑会话存储,
            I内容块编辑会话文件存储 内容块编辑会话文件存储,
            I内容块文档转换器 内容块文档转换器,
            I文件哈希服务 文件哈希服务,
            I本地Word启动器 本地Word启动器)
        {
            _内容块编辑会话存储 = 内容块编辑会话存储;
            _内容块编辑会话文件存储 = 内容块编辑会话文件存储;
            _内容块文档转换器 = 内容块文档转换器;
            _文件哈希服务 = 文件哈希服务;
            _本地Word启动器 = 本地Word启动器;
        }

        public 内容块编辑会话 创建会话(
            string 题库键,
            内容块 内容块,
            内容块版本? 当前版本,
            bool 是否打开Word)
        {
            var 会话ID = Guid.NewGuid().ToString("N");
            var 编辑文件路径 = _内容块编辑会话文件存储.获取编辑文件路径(题库键, 会话ID);

            if (当前版本 == null)
            {
                _内容块文档转换器.创建空白内容块文件(编辑文件路径);
            }
            else
            {
                _内容块编辑会话文件存储.复制文件(当前版本.Docx路径, 编辑文件路径);
            }

            var 基准Hash = _文件哈希服务.计算SHA256(编辑文件路径);
            var 会话 = 内容块编辑会话.创建(会话ID, 题库键, 内容块.Id, 编辑文件路径, 当前版本?.Id, 基准Hash);
            _内容块编辑会话存储.保存(会话);
            _内容块编辑会话文件存储.写入会话信息(会话);

            if (是否打开Word)
            {
                try
                {
                    _本地Word启动器.打开文档(编辑文件路径);
                    会话.标记已打开();
                }
                catch (Exception ex)
                {
                    会话.标记失败(ex.Message);
                    _内容块编辑会话文件存储.写入会话信息(会话);
                    throw;
                }
            }
            else
            {
                会话.标记编辑中未打开Word();
            }

            _内容块编辑会话文件存储.写入会话信息(会话);
            return 会话;
        }
    }
}

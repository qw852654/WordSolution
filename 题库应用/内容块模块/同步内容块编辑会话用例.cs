using System;
using 题库核心.内容块模块.契约;
using 题库核心.内容块模块.领域;

namespace 题库应用.内容块模块
{
    public class 同步内容块编辑会话用例
    {
        private static readonly TimeSpan 自动同步最短等待时间 = TimeSpan.FromSeconds(10);

        private readonly I内容块编辑会话存储 _内容块编辑会话存储;
        private readonly I内容块编辑会话文件存储 _内容块编辑会话文件存储;
        private readonly I编辑文件稳定性检测器 _编辑文件稳定性检测器;
        private readonly I文件哈希服务 _文件哈希服务;
        private readonly I内容块仓储 _内容块仓储;
        private readonly I内容块文件存储 _内容块文件存储;
        private readonly I内容块预览生成器 _内容块预览生成器;
        private readonly I内容块文档转换器 _内容块文档转换器;

        public 同步内容块编辑会话用例(
            I内容块编辑会话存储 内容块编辑会话存储,
            I内容块编辑会话文件存储 内容块编辑会话文件存储,
            I编辑文件稳定性检测器 编辑文件稳定性检测器,
            I文件哈希服务 文件哈希服务,
            I内容块仓储 内容块仓储,
            I内容块文件存储 内容块文件存储,
            I内容块预览生成器 内容块预览生成器,
            I内容块文档转换器 内容块文档转换器)
        {
            _内容块编辑会话存储 = 内容块编辑会话存储;
            _内容块编辑会话文件存储 = 内容块编辑会话文件存储;
            _编辑文件稳定性检测器 = 编辑文件稳定性检测器;
            _文件哈希服务 = 文件哈希服务;
            _内容块仓储 = 内容块仓储;
            _内容块文件存储 = 内容块文件存储;
            _内容块预览生成器 = 内容块预览生成器;
            _内容块文档转换器 = 内容块文档转换器;
        }

        public 内容块编辑会话结果? 执行(string 会话ID, bool 强制同步 = false)
        {
            var 会话 = _内容块编辑会话存储.获取(会话ID);
            if (会话 == null)
            {
                return null;
            }

            lock (会话)
            {
                if (会话.是终态())
                {
                    return 内容块编辑会话结果.从会话(会话);
                }

                try
                {
                    if (!强制同步 && DateTime.Now - 会话.创建时间 < 自动同步最短等待时间)
                    {
                        return 内容块编辑会话结果.从会话(会话);
                    }

                    var 检测结果 = _编辑文件稳定性检测器.检测(会话.编辑文件路径);
                    会话.记录检测(检测结果);
                    _内容块编辑会话文件存储.写入会话信息(会话);

                    if (!检测结果.文件存在)
                    {
                        会话.标记失败("编辑文件不存在。");
                        _内容块编辑会话文件存储.写入会话信息(会话);
                        return 内容块编辑会话结果.从会话(会话);
                    }

                    if (检测结果.锁文件存在 || !检测结果.可独占打开)
                    {
                        return 内容块编辑会话结果.从会话(会话);
                    }

                    if (!强制同步 && 会话.稳定检测次数 < 2)
                    {
                        return 内容块编辑会话结果.从会话(会话);
                    }

                    return 内容块编辑会话结果.从会话(执行同步(会话));
                }
                catch (Exception ex)
                {
                    会话.标记失败(ex.Message);
                    _内容块编辑会话文件存储.写入会话信息(会话);
                    return 内容块编辑会话结果.从会话(会话);
                }
            }
        }

        private 内容块编辑会话 执行同步(内容块编辑会话 会话)
        {
            会话.标记同步中();
            _内容块编辑会话文件存储.写入会话信息(会话);

            var 当前Hash = _文件哈希服务.计算SHA256(会话.编辑文件路径);
            if (string.Equals(当前Hash, 会话.基准Hash, StringComparison.OrdinalIgnoreCase))
            {
                会话.标记无变化();
                _内容块编辑会话文件存储.写入会话信息(会话);
                return 会话;
            }

            var 内容块 = _内容块仓储.GetById(会话.内容块ID);
            if (内容块 == null)
            {
                会话.标记失败("内容块不存在。");
                _内容块编辑会话文件存储.写入会话信息(会话);
                return 会话;
            }

            var 版本号 = _内容块仓储.获取下一个版本号(会话.内容块ID);
            var 内容块文件路径 = _内容块文件存储.获取内容块文件路径(会话.题库键, 会话.内容块ID, 版本号, ".docx");
            _内容块编辑会话文件存储.复制文件(会话.编辑文件路径, 内容块文件路径);

            var 预览文件路径 = _内容块文件存储.获取内容块预览文件路径(会话.题库键, 会话.内容块ID, 版本号);
            _内容块预览生成器.生成HTML预览(内容块文件路径, 预览文件路径);

            var 纯文本内容 = _内容块文档转换器.提取纯文本(内容块文件路径);
            var 新版本 = 内容块版本.创建(会话.内容块ID, 版本号, 内容块文件路径, 预览文件路径, 纯文本内容, true);
            _内容块仓储.增加版本并设为当前(内容块, 新版本);

            会话.标记已同步(新版本.Id, 新版本.版本号);
            _内容块编辑会话文件存储.写入会话信息(会话);
            return 会话;
        }
    }
}

using System;
using 题库核心.内容块模块.契约;
using 题库核心.内容块模块.领域;

namespace 题库应用.内容块模块
{
    public class 创建新内容块编辑会话用例
    {
        private readonly I内容块仓储 _内容块仓储;
        private readonly 编辑会话创建帮助类 _编辑会话创建帮助类;

        public 创建新内容块编辑会话用例(
            I内容块仓储 内容块仓储,
            编辑会话创建帮助类 编辑会话创建帮助类)
        {
            _内容块仓储 = 内容块仓储;
            _编辑会话创建帮助类 = 编辑会话创建帮助类;
        }

        public 内容块编辑会话结果 执行(string 题库键, 创建新内容块编辑会话的请求 请求)
        {
            if (请求 == null)
            {
                throw new ArgumentNullException(nameof(请求));
            }

            var 新内容块 = 内容块.创建(
                请求.标题,
                请求.摘要,
                请求.内容块类型 ?? 内容块类型.知识点,
                请求.内容块状态 ?? 内容块状态.草稿,
                请求.内容块结构类型,
                请求.是否允许子块);
            _内容块仓储.增加内容块(新内容块);

            var 会话 = _编辑会话创建帮助类.创建会话(题库键, 新内容块, null, 请求.是否打开Word ?? true);
            return 内容块编辑会话结果.从会话(会话);
        }
    }
}
